-- 0011_route_stops.sql
-- Промежуточные точки маршрута, которые добавляет заказчик: А (база) → Б (забор груза) →
-- [1, 2, … — промежуточные точки по порядку] → В (получатель). Справочные точки маршрута для
-- отображения, расчёта расстояния и проверок; команд дрону платформа не передаёт.
-- Формат: [{"lat": .., "lon": .., "address": "..", "note": ".."}], не более 5 точек.

ALTER TABLE routes
    ADD COLUMN stops jsonb NOT NULL DEFAULT '[]'::jsonb
        CHECK (jsonb_typeof(stops) = 'array' AND jsonb_array_length(stops) <= 5);
